import { test, expect } from '@playwright/test';
test('recinto salvo recebe uma ave e bloqueia exclusão até a mudança', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 1800 });
  await page.goto('/');
  await page.getByRole('button', { name: 'Começar meu criatório', exact: true }).click();
  await page.getByRole('button', { name: 'Recintos', exact: true }).click();
  await page.getByRole('button', { name: 'Novo recinto', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Nome *', { exact: true }).fill('Viveiro teste');
  await page.getByRole('dialog').getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Viveiro teste' })).toBeVisible();
  await page.getByRole('button', { name: 'Aves', exact: true }).click();
  await page.getByRole('button', { name: 'Cadastrar ave', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Identificação ou anilha *', { exact: true }).fill('R-01');
  await dialog.getByRole('combobox', { name: 'Espécie *', exact: true }).selectOption({ index: 1 });
  await dialog.locator('summary').filter({ hasText: 'Recinto e observações' }).click();
  await dialog.getByRole('combobox', { name: 'Recinto', exact: true }).selectOption('Viveiro teste');
  await dialog.getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'Recintos', exact: true }).click();
  await expect(page.getByText('disponível · 1 aves', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Excluir Viveiro teste', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Mova todas as aves');
  await page.getByRole('dialog').getByRole('button', { name: 'Cancelar', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Recintos', exact: true }).click();
  await expect(page.getByText('disponível · 1 aves', { exact: true })).toBeVisible();
  await expect.poll(() => page.locator('#main-scroll .cached-view').evaluate(e => getComputedStyle(e.parentElement as HTMLElement).filter)).toBe('blur(0px)');
  await page.screenshot({ path: '/tmp/browser/recintos/desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/browser/recintos/mobile.png' });
});